/**
 * Low-poly figures, drawn flat-shaded like the shop's glasses holders.
 *
 * Every figure takes one filament colour and derives five shades from it
 * (light from the upper left: left facets lighter, right facets darker), so the
 * colour picker on a product page recolours the whole piece. A masked stripe
 * pattern on top gives the visible layer lines of a real FDM print.
 *
 * viewBox is 400 x 500 for every figure, floor at y ~ 455.
 */

function mix(hex, amt) {
  const [r, g, b] = hexToRgb(hex);
  const t = amt < 0 ? 0 : 255;
  const k = Math.abs(amt);
  const c = (x) => Math.round(x + (t - x) * k);
  return `rgb(${c(r)},${c(g)},${c(b)})`;
}

export function shades(hex) {
  return {
    d2: mix(hex, -0.55),
    d1: mix(hex, -0.3),
    m: mix(hex, -0.08),
    l1: mix(hex, 0.1),
    l2: mix(hex, 0.32),
  };
}

const P = ({ p, f, o }) => <polygon points={p} fill={f} opacity={o} />;

const ngon = (cx, cy, r, n = 8, rot = Math.PI / 8) =>
  Array.from({ length: n }, (_, i) => {
    const a = rot + (i / n) * Math.PI * 2;
    return `${(cx + r * Math.cos(a)).toFixed(1)},${(cy + r * Math.sin(a)).toFixed(1)}`;
  }).join(' ');

